# -*- coding: utf-8 -*-
import pandas as pd, numpy as np
pd.set_option('display.width',200)
df = pd.read_excel('共享单车数据十万条1.xls')
df['start'] = pd.to_datetime(df['开始时间'], format='%m/%d/%Y %H:%M', errors='coerce')
df['end']   = pd.to_datetime(df['结束时间'], format='%m/%d/%Y %H:%M', errors='coerce')
print('start_time nulls:', df['start'].isna().sum(), 'end nulls:', df['end'].isna().sum())
print('time span:', df['start'].min(), '->', df['start'].max())
print('days covered:', df['start'].dt.date.nunique())
print('trips/day desc:'); print(df.groupby(df['start'].dt.date).size().describe())
print('per-day head:'); print(df.groupby(df['start'].dt.date).size().head(10).to_string())
print('per-day tail:'); print(df.groupby(df['start'].dt.date).size().tail(5).to_string())
print('\n--- duration ---')
print(df['骑行时间'].describe())
print('duration<=0:', (df['骑行时间']<=0).sum(), ' >180:', (df['骑行时间']>180).sum())
print('会员骑行时间 uniq:', df['会员骑行时间'].unique()[:5], 'nonzero:', (df['会员骑行时间']!=0).sum())
print('\n--- category ---')
print(df['骑行路线类别'].value_counts(dropna=False))
print(df['会员类型'].value_counts(dropna=False))
print('\n--- stations ---')
print('start stations:', df['开始站点id'].nunique(), 'end stations:', df['结束站点'].nunique())
print('start range', df['开始站点id'].min(), df['开始站点id'].max())
ss=set(df['开始站点id']); es=set(df['结束站点'])
print('only in start:', len(ss-es), 'only in end:', len(es-ss))
print('\n--- bikes ---')
print('bikes:', df['车辆id'].nunique())
vc=df['车辆id'].value_counts()
print(vc.describe())
print('top bikes:', vc.head(5).to_dict())
print('\n--- duplicates ---')
print('dup trip_id:', df['trip_id'].duplicated().sum())
print('full dup rows:', df.duplicated(subset=['开始时间','开始站点id','车辆id','结束时间']).sum())
print('\n--- coords ---')
print(df[['开始经度','开始维度','结束经度','结束维度']].describe().to_string())
